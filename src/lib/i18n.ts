// ─── Translation function ─────────────────────────────────────────────────────
export function t(
  locale: Locale,
  key: string,
  vars?: Record<string, string | number>,
): string {
  let str = dict[locale]?.[key] ?? dict["es"]?.[key] ?? key;
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      str = str.replace(`{${k}}`, String(v));
    });
  }
  return str;
}
